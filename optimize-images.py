#!/usr/bin/env python3
"""Build display-sized WebP variants and a browser manifest.

Originals stay in images/. The site requests images/opt/* instead.
Only photos referenced from the site source are resized, so spare files
in a project folder are left alone. Re-run after adding or replacing a photo:

    python3 optimize-images.py
"""
import json
import re
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "images"
OUT = SRC / "opt"
WIDTHS = (640, 960, 1600)
QUALITY = 76

OUT.mkdir(exist_ok=True)
manifest = {}
referenced = set()
ref_pattern = re.compile(r"images/[A-Za-z0-9_./-]+\.(?:jpe?g|png|webp)", re.I)
for name in ("projects.js", "index.html", "project.html", "resume.html"):
    referenced.update(ref_pattern.findall((ROOT / name).read_text()))
referenced = {item for item in referenced if not item.startswith("images/opt/")}

for path in sorted(SRC.rglob("*")):
    if not path.is_file():
        continue
    if "opt" in path.relative_to(SRC).parts:
        continue
    if path.suffix.lower() not in {".jpg", ".jpeg", ".png", ".webp"}:
        continue
    key = "images/" + path.relative_to(SRC).as_posix()
    if key not in referenced:
        continue
    with Image.open(path) as im:
        im = ImageOps.exif_transpose(im) or im
        has_alpha = im.mode in ("RGBA", "LA") or (
            im.mode == "P" and "transparency" in im.info
        )
        im = im.convert("RGBA" if has_alpha else "RGB")
        src_w = im.width
        variants = []
        targets = [w for w in WIDTHS if w < src_w]
        if not targets or targets[-1] != src_w:
            targets.append(min(src_w, WIDTHS[-1]))
        # de-dupe while keeping order
        seen = set()
        ordered = []
        for w in targets:
            if w not in seen and w > 0:
                seen.add(w)
                ordered.append(w)
        for w in ordered:
            height = max(1, round(im.height * w / src_w))
            resized = im if w == src_w else im.resize((w, height), Image.Resampling.LANCZOS)
            name = f"{path.stem}-{w}.webp"
            dest = OUT / name
            resized.save(dest, "WEBP", quality=QUALITY, method=6)
            variants.append({"w": w, "src": f"images/opt/{name}"})
            print(f"{path.name:28} {src_w:4} -> {w:4}  {dest.stat().st_size/1024:7.1f} KB")
        manifest[key] = variants

manifest_js = (
    "// Generated by optimize-images.py. Do not edit.\n"
    "const OPTIMIZED = "
    + json.dumps(manifest, indent=2)
    + ";\n"
)
(ROOT / "opt-manifest.js").write_text(manifest_js)
video = OUT / "chessinator-video.mp4"
if video.exists():
    extra = (
        "const OPTIMIZED_VIDEO = "
        + json.dumps({"images/chessinator/chessinator-video.mov": "images/opt/chessinator-video.mp4"})
        + ";\n"
    )
    with (ROOT / "opt-manifest.js").open("a") as fh:
        fh.write(extra)
print(f"manifest entries: {len(manifest)}")
